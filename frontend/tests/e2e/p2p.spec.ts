import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

const screenshots = path.resolve(process.cwd(), '..', 'artifacts', 'screenshots')

test('complete requisition to payment flow and verify responsive persistence', async ({ page, browserName }) => {
  await mkdir(screenshots, { recursive: true })
  const consoleErrors: string[] = []
  const failedRequests: string[] = []
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  page.on('requestfailed', request => failedRequests.push(`${request.method()} ${request.url()} ${request.failure()?.errorText ?? ''}`))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Demo role').selectOption('admin')
  await page.getByRole('button', { name: /Open workspace/ }).click()
  await expect(page.getByRole('heading', { name: 'Procurement overview' })).toBeVisible()
  await page.screenshot({ path: path.join(screenshots, 'dashboard-1440.png'), fullPage: true })

  const suffix = `${Date.now()}`
  const supplierCode = `SUP-E2E-${suffix}`
  const supplierName = `Juniper E2E ${suffix}`
  await page.goto('/suppliers')
  await page.getByRole('button', { name: 'Add supplier' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Supplier ID').fill(supplierCode)
  await dialog.getByLabel('Legal or trading name').fill(supplierName)
  await dialog.getByLabel('Contact person').fill('Test Buyer')
  await dialog.getByLabel('Email address').fill(`e2e-${suffix}@example.com`)
  await dialog.getByRole('button', { name: 'Register supplier' }).click()
  await expect(page.getByRole('button', { name: supplierName })).toBeVisible()
  await page.screenshot({ path: path.join(screenshots, 'suppliers-1366.png'), fullPage: true })

  await page.getByLabel('Switch demo role').selectOption('requester')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('requester')
  await page.getByRole('link', { name: 'Requisitions' }).click()
  await page.getByRole('button', { name: 'New requisition' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Requested by').fill('Nila Iyer')
  await dialog.getByLabel('Department').selectOption({ label: 'Operations' })
  await dialog.getByLabel('Business need').fill(`Quarterly field notebooks ${suffix}`)
  await dialog.getByLabel('Item or service description').fill('Field notebooks')
  await dialog.getByLabel('Quantity').fill('2')
  await dialog.getByLabel('Unit price (₹)').fill('500')
  await dialog.getByRole('button', { name: 'New requisition' }).click()
  const reqRow = page.getByRole('row').filter({ hasText: `Quarterly field notebooks ${suffix}` })
  await expect(reqRow).toContainText('Submitted')
  const reqNumber = (await reqRow.locator('td').first().innerText()).trim()

  await page.getByLabel('Switch demo role').selectOption('approver')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('approver')
  await expect(reqRow.getByRole('button', { name: 'Approve' })).toBeVisible()
  await reqRow.getByRole('button', { name: 'Approve' }).click()
  await expect(reqRow).toContainText('Approved')

  await page.getByLabel('Switch demo role').selectOption('procurement')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('procurement')
  await page.getByRole('link', { name: 'Purchase orders' }).click()
  await page.getByRole('button', { name: 'Create purchase order' }).click()
  dialog = page.getByRole('dialog')
  await dialog.locator('select[name="supplier_id"]').selectOption({ label: `${supplierName} · ${supplierCode}` })
  await dialog.getByLabel('Approved requisition').selectOption({ label: `${reqNumber} · Operations` })
  await dialog.getByLabel('Expected delivery').fill(new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10))
  await dialog.getByLabel('Item or service description').fill('Field notebooks')
  await dialog.getByLabel('Quantity').fill('2')
  await dialog.getByLabel('Unit price (₹)').fill('500')
  await dialog.getByLabel('GST rate').selectOption('1800')
  await dialog.getByRole('button', { name: 'Create purchase order' }).click()
  const poRow = page.getByRole('row').filter({ hasText: supplierName })
  await expect(poRow).toContainText('Draft')
  const poNumber = (await poRow.locator('td').first().innerText()).trim()

  await page.getByLabel('Switch demo role').selectOption('approver')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('approver')
  await poRow.getByRole('button', { name: 'Release order' }).click()
  await expect(poRow).toContainText('Open')

  await page.getByLabel('Switch demo role').selectOption('receiving')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('receiving')
  await page.getByRole('link', { name: 'Goods receipts' }).click()
  await page.getByRole('button', { name: 'Record receipt' }).click()
  dialog = page.getByRole('dialog')
  await dialog.locator('select[name="purchase_order_id"]').selectOption({ label: `${poNumber} · ${supplierName}` })
  await dialog.getByLabel('Received by').fill('Nila Iyer')
  await dialog.getByLabel('Quantity received').fill('2')
  await dialog.getByLabel('Quantity accepted').fill('2')
  await dialog.getByRole('button', { name: 'Record receipt' }).click()
  await expect(page.getByRole('row').filter({ hasText: poNumber })).toContainText('2.000 received')

  await page.getByLabel('Switch demo role').selectOption('ap')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('ap')
  await page.getByRole('link', { name: 'Invoices' }).click()
  await page.getByRole('button', { name: 'Record invoice' }).click()
  dialog = page.getByRole('dialog')
  await dialog.locator('select[name="supplier_id"]').selectOption({ label: `${supplierName} · ${supplierCode}` })
  await dialog.locator('select[name="purchase_order_id"]').selectOption({ label: poNumber })
  const invoiceNumber = `INV-E2E-${suffix}`
  await dialog.getByLabel('Supplier invoice number').fill(invoiceNumber)
  await dialog.getByLabel('Matching method').selectOption('THREE_WAY')
  await dialog.getByLabel('Line description').fill('Field notebooks')
  await dialog.getByLabel('Quantity').fill('2')
  await dialog.getByLabel('Unit price (₹)').fill('500')
  await dialog.getByLabel('GST rate').selectOption('1800')
  await dialog.getByRole('button', { name: 'Record invoice' }).click()
  const invoiceRow = page.getByRole('row').filter({ hasText: invoiceNumber })
  await expect(invoiceRow).toContainText('Matched')
  await expect(invoiceRow).toContainText('Pending Approval')
  await expect(invoiceRow).toContainText('₹1,180')
  await page.screenshot({ path: path.join(screenshots, 'invoices-1440.png'), fullPage: true })

  await page.getByLabel('Switch demo role').selectOption('approver')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('approver')
  await invoiceRow.getByRole('button', { name: 'Approve' }).click()
  await expect(invoiceRow).toContainText('Approved')
  await page.getByLabel('Switch demo role').selectOption('ap')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('ap')
  await page.getByRole('link', { name: 'Payments' }).click()
  await page.getByRole('button', { name: 'Record payment' }).click()
  dialog = page.getByRole('dialog')
  const invoiceSelect = dialog.getByLabel('Approved invoice')
  const invoiceOption = invoiceSelect.locator('option').filter({ hasText: invoiceNumber })
  await invoiceSelect.selectOption((await invoiceOption.getAttribute('value')) ?? '')
  await dialog.getByLabel('Payment amount (₹)').fill('1180')
  await dialog.getByLabel('Payment method').selectOption('NEFT')
  await dialog.getByRole('button', { name: 'Record payment' }).click()
  await expect(page.getByRole('row').filter({ hasText: invoiceNumber })).toContainText('₹1,180')

  await page.getByRole('link', { name: 'Reconciliation' }).click()
  let reconRow = page.getByRole('row').filter({ hasText: invoiceNumber })
  await expect(reconRow).toContainText('Paid')
  await expect(reconRow).toContainText('₹0')
  await page.screenshot({ path: path.join(screenshots, 'reconciliation-1440.png'), fullPage: true })
  await page.reload()
  await page.getByRole('link', { name: 'Reconciliation' }).click()
  reconRow = page.getByRole('row').filter({ hasText: invoiceNumber })
  await expect(reconRow).toContainText('₹0')

  await page.getByLabel('Switch demo role').selectOption('viewer')
  await expect(page.getByLabel('Switch demo role')).toHaveValue('viewer')
  await page.goto('/suppliers')
  await expect(page.getByRole('heading', { name: 'Suppliers' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add supplier' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Import CSV' })).toHaveCount(0)

  for (const width of [1440, 1366, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : width === 768 ? 1024 : 900 })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Procurement overview' })).toBeVisible()
    await expect(page.getByText('Fictional demonstration records')).toBeVisible()
    await page.screenshot({ path: path.join(screenshots, `dashboard-${width}.png`), fullPage: true })
    const dimensions = await page.evaluate(() => ({ body: document.body.scrollWidth, viewport: window.innerWidth }))
    expect(dimensions.body).toBeLessThanOrEqual(dimensions.viewport + 1)
    for (const [route, heading] of [['/suppliers', 'Suppliers'], ['/invoices', 'Invoices'], ['/payments', 'Payments'], ['/reconciliation', 'Reconciliation'], ['/reports', 'Reports & exports']] as const) {
      await page.goto(route)
      await expect(page.getByRole('heading', { name: heading }).first()).toBeVisible()
      const pageDimensions = await page.evaluate(() => ({ body: document.body.scrollWidth, viewport: window.innerWidth }))
      expect(pageDimensions.body).toBeLessThanOrEqual(pageDimensions.viewport + 1)
      if (width === 390) await page.screenshot({ path: path.join(screenshots, `${route.slice(1)}-${width}.png`), fullPage: true })
    }
  }
  expect(browserName).toBe('chromium')
  expect(consoleErrors).toEqual([])
  expect(failedRequests).toEqual([])
})
